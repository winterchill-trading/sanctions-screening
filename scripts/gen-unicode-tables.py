#!/usr/bin/env python3
"""Writes src/unicode_data.ml from Python's unicodedata module.

Three tables, all over the Basic Multilingual Plane minus Hangul syllables and CJK
compatibility ideographs (scripts that Latinisation does not cover):

- the full compatibility decomposition (NFKD) of every code point that has one;
- the ranges of combining marks (general categories Mn, Mc, Me);
- the simple lowercase mapping of every code point whose lowercase is one other code point.

Run it again when moving to a newer Python to pick up a newer Unicode version:

    python3 scripts/gen-unicode-tables.py > src/unicode_data.ml
"""

import sys
import unicodedata


def wanted(cp):
    if cp < 0x80:
        return False
    if 0xAC00 <= cp <= 0xD7A3:  # Hangul syllables
        return False
    if 0xD800 <= cp <= 0xDFFF:  # surrogates
        return False
    if 0xF900 <= cp <= 0xFAFF:  # CJK compatibility ideographs
        return False
    if 0x3000 <= cp <= 0x9FFF:  # CJK, kana, CJK compatibility
        return False
    return True


def main():
    decomp = []
    lower = []
    marks = []
    for cp in range(0x80, 0x10000):
        if not wanted(cp):
            continue
        ch = chr(cp)
        d = unicodedata.normalize("NFKD", ch)
        if d != ch:
            decomp.append((cp, [ord(c) for c in d]))
        if unicodedata.category(ch) in ("Mn", "Mc", "Me"):
            if marks and marks[-1][1] == cp - 1:
                marks[-1][1] = cp
            else:
                marks.append([cp, cp])
        lo = ch.lower()
        if lo != ch and len(lo) == 1:
            lower.append((cp, ord(lo)))
    out = sys.stdout
    out.write("(* Generated by scripts/gen-unicode-tables.py from Unicode %s.\n"
              "   Do not edit by hand. *)\n\n" % unicodedata.unidata_version)
    out.write('let unicode_version = "%s"\n\n' % unicodedata.unidata_version)
    out.write("let decomp_keys = [|")
    out.write(";".join("0x%X" % cp for cp, _ in decomp))
    out.write("|]\n\n")
    offsets = [0]
    flat = []
    for _, cps in decomp:
        flat.extend(cps)
        offsets.append(len(flat))
    out.write("let decomp_offsets = [|")
    out.write(";".join(str(o) for o in offsets))
    out.write("|]\n\n")
    out.write("let decomp_values = [|")
    out.write(";".join("0x%X" % cp for cp in flat))
    out.write("|]\n\n")
    out.write("let mark_ranges = [|")
    out.write(";".join("0x%X;0x%X" % (a, b) for a, b in marks))
    out.write("|]\n\n")
    out.write("let lower_keys = [|")
    out.write(";".join("0x%X" % cp for cp, _ in lower))
    out.write("|]\n\n")
    out.write("let lower_values = [|")
    out.write(";".join("0x%X" % lo for _, lo in lower))
    out.write("|]\n")


if __name__ == "__main__":
    main()
