#!/usr/bin/env python3
"""Writes src/country_names.ml: country names to ISO 3166 alpha-2 codes, taken from the
CountryValues of OFAC's advanced XML (public data), plus the spellings the UK list uses.

    python3 scripts/gen-country-names.py lists/sdn_advanced.xml > src/country_names.ml
"""

import re
import sys

# Spellings in the UK and EU lists that OFAC writes differently.
EXTRA = {
    "Russia": "RU", "Russian Federation": "RU", "Syria": "SY", "Syrian Arab Republic": "SY",
    "Iran": "IR", "Iran (Islamic Republic of)": "IR", "North Korea": "KP",
    "Democratic People's Republic of Korea": "KP", "South Korea": "KR",
    "Republic of Korea": "KR", "United Kingdom": "GB", "UK": "GB",
    "United States": "US", "USA": "US", "Burma": "MM", "Myanmar": "MM",
    "Democratic Republic of the Congo": "CD", "Republic of the Congo": "CG",
    "Ivory Coast": "CI", "Cote d'Ivoire": "CI", "Turkey": "TR", "Turkiye": "TR",
    "Czechia": "CZ", "Moldova": "MD", "Venezuela": "VE", "Laos": "LA", "Vietnam": "VN",
    "Palestinian Territories": "PS", "Occupied Palestinian Territories": "PS",
    "The Gambia": "GM", "Gambia": "GM", "The Bahamas": "BS", "Bahamas": "BS",
    "Macedonia": "MK", "North Macedonia": "MK", "Kyrgyzstan": "KG", "Belarus": "BY",
    "Ukraine": "UA", "Libya": "LY", "Tanzania": "TZ", "Bolivia": "BO",
}


def main(path):
    text = open(path, encoding="utf-8").read()
    pairs = {}
    for iso2, name in re.findall(r'<Country ID="\d+" ISO2="([A-Z]{2})">([^<]+)</Country>', text):
        pairs[name.strip()] = iso2
    pairs.update(EXTRA)
    sys.stdout.write("(* Generated by scripts/gen-country-names.py from OFAC's advanced XML\n"
                     "   country values and the UK list's spellings. Do not edit by hand. *)\n\n")
    sys.stdout.write("let all = [\n")
    for name in sorted(pairs):
        sys.stdout.write("  %s, %s;\n" % (ocaml_string(name), ocaml_string(pairs[name])))
    sys.stdout.write("]\n")


def ocaml_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main(sys.argv[1])
